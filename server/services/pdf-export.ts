import PDFDocument from "pdfkit";
import type { DesignWithDetails } from "@shared/schema";

export async function generateQuiltPDF(designDetails: DesignWithDetails): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "LETTER",
        margins: { top: 50, bottom: 50, left: 50, right: 50 },
        info: {
          Title: `${designDetails.design.name} - Quilt Pattern`,
          Author: "Quilter's AI",
          Subject: "Quilting Pattern",
        },
      });

      const chunks: Buffer[] = [];
      doc.on("data", (chunk) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // Title Page
      doc
        .fontSize(24)
        .font("Helvetica-Bold")
        .text(designDetails.design.name, { align: "center" });
      
      doc.moveDown(0.5);
      doc.fontSize(12).font("Helvetica").text("Generated by Quilter's AI", { align: "center" });
      doc.moveDown(2);

      // Quilt Overview
      doc.fontSize(16).font("Helvetica-Bold").text("Quilt Overview");
      doc.moveDown(0.5);
      doc.fontSize(10).font("Helvetica");

      const metadata = designDetails.design.metadata as any;
      const quiltWidth = metadata?.quiltWidth || 60;
      const quiltHeight = metadata?.quiltHeight || 80;

      doc.text(`Block Pattern: ${designDetails.design.blockPattern}`);
      doc.text(`Layout: ${designDetails.design.layoutStrategy}`);
      doc.text(`Size: ${quiltWidth}" × ${quiltHeight}"`);
      doc.text(`Difficulty: ${"★".repeat(designDetails.design.difficulty)} (${designDetails.design.difficulty}/5)`);
      doc.text(`Estimated Time: ${designDetails.design.estimatedHours || "N/A"} hours`);
      doc.text(`Total Fabric Yardage: ${designDetails.design.totalYardage?.toFixed(2)} yards`);
      doc.moveDown(2);

      // Materials Summary
      doc.fontSize(16).font("Helvetica-Bold").text("Materials Required");
      doc.moveDown(0.5);
      doc.fontSize(10).font("Helvetica");

      doc.text(`Backing: ${designDetails.backing.yardage.toFixed(2)} yards (${designDetails.backing.widthIn}" × ${designDetails.backing.heightIn}")`);
      doc.text(`  ${designDetails.backing.piecingPlan || ""}`);
      doc.text(`Batting: ${designDetails.batting.widthIn}" × ${designDetails.batting.heightIn}"`);
      doc.text(`Binding: ${designDetails.binding.yardage.toFixed(2)} yards (${designDetails.binding.stripWidthIn}" strips, ${designDetails.binding.totalLengthIn}" total)`);
      doc.moveDown(2);

      // 1-Inch Test Square
      doc.fontSize(14).font("Helvetica-Bold").text("Printer Calibration Test");
      doc.moveDown(0.5);
      doc.fontSize(9).font("Helvetica");
      doc.text("Measure this square. It should be exactly 1 inch × 1 inch.");
      doc.text("If not, adjust your printer settings to 100% scale (no fit-to-page).");
      doc.moveDown(0.3);
      
      const testSquareX = doc.x;
      const testSquareY = doc.y;
      doc.rect(testSquareX, testSquareY, 72, 72).stroke(); // 72 points = 1 inch
      doc.moveDown(3);

      // Seam Allowance Legend
      doc.fontSize(10).font("Helvetica-Bold").text("Important: Seam Allowance");
      doc.fontSize(9).font("Helvetica");
      doc.text("All measurements in the cut list include 1/4\" seam allowance on all sides.");
      doc.text("For example, a 3.5\" square will finish at 3\" after seaming.");
      doc.moveDown(2);

      // New page for Cut List
      doc.addPage();
      doc.fontSize(16).font("Helvetica-Bold").text("Fabric Cut List");
      doc.moveDown(1);

      // Cut List Table
      const tableTop = doc.y;
      const colWidths = [80, 100, 80, 60, 70];
      const headers = ["Fabric Color", "Piece Type", "Size", "Qty", "Yardage"];
      
      // Table headers
      doc.fontSize(10).font("Helvetica-Bold");
      let currentX = doc.x;
      headers.forEach((header, i) => {
        doc.text(header, currentX, tableTop, { width: colWidths[i], align: "left" });
        currentX += colWidths[i];
      });

      doc.moveTo(doc.x, tableTop + 15).lineTo(doc.x + colWidths.reduce((a, b) => a + b, 0), tableTop + 15).stroke();

      // Table rows
      doc.fontSize(9).font("Helvetica");
      let currentY = tableTop + 20;

      // Group cut list items by fabric color
      const fabricGroups = new Map<string, typeof designDetails.cutList>();
      for (const item of designDetails.cutList) {
        if (!fabricGroups.has(item.fabricColor)) {
          fabricGroups.set(item.fabricColor, []);
        }
        fabricGroups.get(item.fabricColor)!.push(item);
      }

      // Render grouped rows
      for (const [color, items] of Array.from(fabricGroups)) {
        for (const item of items) {
          if (currentY > 700) {
            doc.addPage();
            currentY = 50;
          }

          currentX = doc.x;
          const rowData = [
            color,
            item.pieceType,
            `${item.widthIn}" × ${item.heightIn}"`,
            item.quantity.toString(),
            `${item.yardage.toFixed(3)} yd`,
          ];

          rowData.forEach((text, i) => {
            doc.text(text, currentX, currentY, { width: colWidths[i], align: "left" });
            currentX += colWidths[i];
          });

          currentY += 15;
        }
      }

      // Total yardage
      doc.moveDown(1);
      doc.fontSize(10).font("Helvetica-Bold");
      const totalFabricYardage = designDetails.cutList.reduce((sum, item) => sum + item.yardage, 0);
      doc.text(`Total Fabric Yardage: ${totalFabricYardage.toFixed(2)} yards`, { align: "right" });

      // New page for Piecing Instructions
      doc.addPage();
      doc.fontSize(16).font("Helvetica-Bold").text("Piecing Instructions");
      doc.moveDown(1);

      doc.fontSize(10).font("Helvetica");
      for (const step of designDetails.steps) {
        if (doc.y > 700) {
          doc.addPage();
        }

        doc.font("Helvetica-Bold").text(`Step ${step.stepNumber}:`);
        doc.font("Helvetica").text(step.instruction, { indent: 20 });
        doc.moveDown(0.5);
      }

      // Quilting suggestions
      if (designDetails.design.quiltingMotifs && designDetails.design.quiltingMotifs.length > 0) {
        doc.moveDown(1);
        doc.fontSize(14).font("Helvetica-Bold").text("Quilting Suggestions");
        doc.moveDown(0.5);
        doc.fontSize(10).font("Helvetica");
        doc.text(`Recommended motifs: ${designDetails.design.quiltingMotifs.join(", ")}`);
      }

      // Buy Supplies Section
      doc.addPage();
      doc.fontSize(16).font("Helvetica-Bold").text("Buy Supplies");
      doc.moveDown(1);
      
      doc.fontSize(9).font("Helvetica");
      doc.text("Get everything you need for this quilt! As an Amazon Associate and affiliate partner,");
      doc.text("we earn from qualifying purchases at no extra cost to you. This helps support Quilter's AI!");
      doc.moveDown(1);

      // Fabric
      doc.fontSize(12).font("Helvetica-Bold").text("📐 Quilting Fabric");
      doc.moveDown(0.5);
      doc.fontSize(9).font("Helvetica");
      doc.text("• Fat Quarter Shop: https://www.fatquartershop.com/?aff=quiltersai");
      doc.text("  Premium quilting fabrics and pre-cuts");
      doc.text("• Missouri Star Quilt Co: https://www.missouriquiltco.com/?aff=quiltersai");
      doc.text("  Wide selection of quilting fabrics");
      doc.moveDown(1);

      // Batting
      doc.fontSize(12).font("Helvetica-Bold").text("🛏️ Batting & Backing");
      doc.moveDown(0.5);
      doc.fontSize(9).font("Helvetica");
      doc.text("• Warm & Natural Batting: https://www.amazon.com/dp/B000YZ7G44?tag=quiltersai-20");
      doc.text("  Popular cotton batting for quilts");
      doc.moveDown(1);

      // Thread
      doc.fontSize(12).font("Helvetica-Bold").text("🪡 Thread");
      doc.moveDown(0.5);
      doc.fontSize(9).font("Helvetica");
      doc.text("• Aurifil Thread Set: https://www.amazon.com/dp/B00JQE7L8O?tag=quiltersai-20");
      doc.text("  Professional quilting thread collection");
      doc.moveDown(1);

      // Tools
      doc.fontSize(12).font("Helvetica-Bold").text("📏 Cutting & Measuring");
      doc.moveDown(0.5);
      doc.fontSize(9).font("Helvetica");
      doc.text("• Rotary Cutter & Mat Set: https://www.amazon.com/dp/B000YZ7IJI?tag=quiltersai-20");
      doc.text("  Essential quilting cutting tools");
      doc.text("• Quilting Ruler Set: https://www.amazon.com/dp/B0000CBJES?tag=quiltersai-20");
      doc.text("  Precision rulers for accurate cutting");

      // Footer on last page
      doc.moveDown(3);
      doc.fontSize(8).font("Helvetica").text(
        "Generated by Quilter's AI - Happy Quilting!",
        { align: "center" }
      );
      doc.text("* Prices and availability subject to change. Links support Quilter's AI development.", { align: "center" });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}
